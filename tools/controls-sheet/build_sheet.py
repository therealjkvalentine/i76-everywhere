def pad_box(M, control, title=None):
    d = M.pad.get(control, {"base": [], "shift": []})
    def lines(items):
        return "".join('<div class="pl">%s%s%s <span class="kk">%s</span></div>' % (
            esc(i["text"]), dag(i["ok"]), (' <i>(%s)</i>' % esc(i["how"])) if i["how"] else "", esc(short_key(i["keys"]))) for i in items)
    unb = M.data["gamepad"]["unbound_controls"].get(control)
    native = ""
    if control == "LS":
        nat = [b for b in M.native_joy if b.analog]
        native = "".join('<div class="pl">%s <span class="kk">native: %s %s</span></div>' % (
            esc(label(M, b.action)), esc(b.analog[0]), esc(b.analog[1])) for b in nat)
    base = native + lines(d["base"])
    if not base:
        base = '<div class="pl un">%s</div>' % esc(unb or "not bound")
    shift = lines(d["shift"])
    return ('<div class="pbox"><div class="pname">%s</div><div class="pbase">%s</div>%s</div>' % (
        esc(title or control), base, ('<div class="pshift"><span class="lb">LB +</span>%s</div>' % shift) if shift else ""))


