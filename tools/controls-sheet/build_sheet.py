PRETTY = {"One": "1", "Two": "2", "Three": "3", "Four": "4", "Five": "5", "Six": "6", "Seven": "7",
          "Eight": "8", "Nine": "9", "Zero": "0", "Comma": ", (comma)", "Period": ". (period)",
          "Minus": "- (minus)", "Equal": "= (equals)", "LeftBracket": "[", "RightBracket": "]",
          "SemiColon": "; (semicolon)", "Quote": "' (quote)",
          "GreyUpArrow": "Up arrow", "GreyDownArrow": "Down arrow", "GreyLeftArrow": "Left arrow",
          "GreyRightArrow": "Right arrow", "GreyPageUp": "Page Up", "GreyPageDown": "Page Down",
          "GreyEnd": "End", "UpArrow": "Up arrow (plain set)", "DownArrow": "Down arrow (plain set)",
          "LeftArrow": "Left arrow (plain set)", "RightArrow": "Right arrow (plain set)",
          "LeftBtn": "Left mouse button", "RightBtn": "Right mouse button", "MiddleBtn": "Middle mouse button",
          "Left/Right": "left / right axis", "Down/Up": "forward / back axis"}


def pretty(tok):
    return PRETTY.get(tok, tok)


def chord_text(tok, mods=frozenset(), dev="keyboard"):
    # tok may arrive lower-cased (from a chord tuple): recover the display form
    for k in PRETTY:
        if k.lower() == tok.lower():
            tok = k
            break
    else:
        if len(tok) == 1:
            tok = tok.upper()
    t = pretty(tok)
    return " + ".join([m.capitalize() if m != "control" else "Ctrl" for m in sorted(mods)] + [t])


def keys_of(bindings, action_set):
    """All triggers of a set of actions, as display strings, in file order, de-duplicated."""
    out = []
    for b in bindings:
        if b.action not in action_set:
            continue
        if b.analog:
            dev = "Joystick 1" if b.analog[0] == "joystick1" else b.analog[0]
            t = "%s, %s" % (dev, pretty(b.analog[1]))
        elif b.tok:
            t = chord_text(b.tok, b.mods, b.dev)
        else:
            continue
        if t not in out:
            out.append(t)
    return out


def compare_rows(M):
    """[(group id, label, stock keys, our keys, changed)] one row per distinct label."""
    rows, seen = [], set()
    order = list(M.actions) + list(M.stock_only)
    for a in order:
        meta = M.actions.get(a) or M.stock_only[a]
        lab = meta["label"]
        if lab in seen:
            continue
        seen.add(lab)
        same = {x for x in order if (M.actions.get(x) or M.stock_only[x])["label"] == lab}
        s = keys_of(M.stock_bindings, same)
        o = keys_of(M.bindings, same)
        rows.append((meta["group"], lab, s, o, s != o))
    return rows


def md_table(M):
    L = [MD_BEGIN, "",
         "| Action | 1997 keys (GOG 2.1.0.17) | This project's map | |",
         "|---|---|---|---|"]
    def cell(keys):
        return "<br>".join("`%s`" % k for k in keys) if keys else "not bound"
    for gid in [g["id"] for g in M.data["groups"]]:
        for g, lab, s, o, changed in compare_rows(M):
            if g == gid:
                L.append("| %s | %s | %s | %s |" % (lab, cell(s), cell(o), "changed" if changed else ""))
    L += ["",
          "Generated from `controls/input.map` (md5 `%s`) and `tools/controls-sheet/stock-2.1.0.17.json` "
          "(GOG's map, md5 `%s`). \"plain set\" = the engine's `UpArrow` / `DownArrow` / `LeftArrow` / "
          "`RightArrow` tokens, as opposed to the `Grey*` set that the dedicated arrow keys send." % (M.map_md5, M.stock["md5"]),
          "", MD_END]
    return "\n".join(L)


def controls_md_state(M):
    """(current text, wanted text) of docs/CONTROLS.md with the generated block refreshed."""
    cur = read(CONTROLS_MD)
    a, b = cur.find(MD_BEGIN), cur.find(MD_END)
    if a < 0 or b < 0:
        return cur, None
    return cur, cur[:a] + md_table(M) + cur[b + len(MD_END):]


