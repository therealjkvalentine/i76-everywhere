def extract_stock(path):
    raw = open(path, "rb").read()
    blocks = parse_map_text(raw.decode("latin-1").replace("\r\n", "\n"))
    out = {"_readme": "Bindings of GOG's own input.map (offline installer 2.1.0.17), as facts: action, sign, device, token per block. "
                      "Written by build_sheet.py --extract-stock; used for the 'stock vs ours' page and the table in docs/CONTROLS.md. "
                      "The game file itself is not in this repo.",
           "source": "input.map from setup_interstate76_2.1.0.17 (GOG offline installer), before any setup script touched it",
           "md5": hashlib.md5(raw).hexdigest(), "blocks": blocks}
    with open(STOCK, "w", encoding="utf-8", newline="\n") as f:
        json.dump(out, f, indent=1)
        f.write("\n")
    print("wrote %s (%d blocks, md5 %s)" % (STOCK, len(blocks), out["md5"]))


def main(argv):
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(errors="replace")
        except Exception:
            pass
    if len(argv) >= 2 and argv[0] == "--extract-stock":
        extract_stock(argv[1])
        return 0
    check_only = "--check" in argv
    M = load()
    M.today = datetime.date.today().isoformat()
    for a in argv:
        if a.startswith("--date="):
            M.today = a[7:]
    findings = check(M)
    cur, want = controls_md_state(M)
    if want is None:
        findings.append("docs/CONTROLS.md has no generated block (markers '%s' ... '%s')" % (MD_BEGIN, MD_END))
    elif check_only and cur != want:
        findings.append("docs/CONTROLS.md: the generated stock-vs-ours table is out of date. Run tools\\controls-sheet\\build.ps1")
    if findings:
        print("controls-sheet: %d finding(s). Nothing was written." % len(findings))
        for f in findings:
            print("  - " + f)
        return 1
    print("controls-sheet: sources agree (map md5 %s, %d actions, %d known mismatch(es) listed)" % (
        M.map_md5, len({b.action for b in M.bindings}), len(M.mismatches)))
    for mid, what in M.mismatches.items():
        print("  known mismatch: " + M.known[mid])
    if check_only:
        return 0
    with open(OUT_HTML, "w", encoding="utf-8", newline="\n") as f:
        f.write(build_html(M))
    print("wrote " + OUT_HTML)
    if cur != want:
        raw = open(CONTROLS_MD, "rb").read()
        nl = "\r\n" if b"\r\n" in raw else "\n"
        with open(CONTROLS_MD, "w", encoding="utf-8", newline="") as f:
            f.write(want.replace("\n", nl))
        print("refreshed the generated table in docs/CONTROLS.md")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
