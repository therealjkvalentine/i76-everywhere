def wrap(text, width):
    lines, cur = [], ""
    for w in text.split():
        if cur and len(cur) + 1 + len(w) > width:
            lines.append(cur)
            cur = w
        else:
            cur = (cur + " " + w).strip()
    if cur:
        lines.append(cur)
    return lines


def keyboard_svg(M):
    P, H, GAP, FGAP = 52.0, 50.0, 3.0, 9.0
    out = []
    y = 0.0
    width = 0.0
    for r, row in enumerate(KB_ROWS):
        x = 0.0
        for legend, tok, w in row:
            kw = w * P
            if legend is None:
                x += kw
                continue
            meta = None
            if tok and tok.startswith("!"):
                meta = M.fixed.get(tok[1:])
                short = meta["key"] if meta else None
            elif tok:
                acts = M.by_key.get(("keyboard", tok.lower()), [])
                if acts:
                    meta = M.actions[acts[0]]
                    short = " / ".join(dict.fromkeys(M.actions[a]["key"] for a in acts))
            g = M.groups[meta["group"]] if meta else None
            fill = g["color"] if g else "#ffffff"
            out.append('<rect x="%.1f" y="%.1f" width="%.1f" height="%.1f" rx="5" fill="%s" stroke="%s" stroke-width="%s"/>' % (
                x + GAP / 2, y + GAP / 2, kw - GAP, H - GAP, fill, "#222" if g else "#aaa", "1.3" if g else "0.8"))
            out.append('<text x="%.1f" y="%.1f" class="%s">%s</text>' % (x + 6, y + 14, "kl" if g else "kl un", esc(legend)))
            if g:
                out.append('<text x="%.1f" y="%.1f" class="kc">%s</text>' % (x + kw - 6, y + 14, esc(g["code"])))
                lines = wrap(short, max(9, int((kw - 8) / 5.2)))[:3]
                y0 = y + 29 + (10 if len(lines) == 1 else 5 if len(lines) == 2 else 0) - (2 if len(lines) == 3 else 0)
                for i, ln in enumerate(lines):
                    out.append('<text x="%.1f" y="%.1f" class="ka" text-anchor="middle">%s</text>' % (x + kw / 2, y0 + i * 9.6, esc(ln)))
            x += kw
        width = max(width, x)
        y += H + (FGAP if r == 0 else 0)
    return '<svg class="kb" viewBox="0 0 %.0f %.0f" xmlns="http://www.w3.org/2000/svg">%s</svg>' % (width, y, "".join(out))


def group_lists(M):
    cols = []
    for g in M.data["groups"]:
        rows, seen = [], set()
        for a, meta in M.actions.items():
            if meta["group"] != g["id"] or meta["label"] in seen:
                continue
            seen.add(meta["label"])
            same = {x for x, m2 in M.actions.items() if m2["label"] == meta["label"]}
            keys = [k for k in keys_of(M.bindings, same) if "mouse button" not in k]
            if keys:
                rows.append((meta["label"], keys))
        for k, meta in M.fixed.items():
            if meta["group"] == g["id"] and meta["label"] not in seen:
                seen.add(meta["label"])
                rows.append((meta["label"], [x for x, m2 in M.fixed.items() if m2["label"] == meta["label"]]))
        def kbds(keys):
            keys = [short_key(k) for k in keys]
            if len(keys) > 2 and all(k.startswith("Shift + ") for k in keys):
                rest = [k[8:] for k in keys]                                # one chip for the four Shift + arrow chords
                keys = ["Shift + " + ("arrows" if set(rest) == {"Up", "Down", "Left", "Right"} else " / ".join(rest))]
            return " ".join("<kbd>%s</kbd>" % esc(k) for k in keys)
        body = "".join('<tr><td class="l">%s</td><td class="k">%s</td></tr>' % (esc(lab), kbds(keys)) for lab, keys in rows)
        cols.append('<div class="grp"><h3><span class="sw" style="background:%s">%s</span>%s</h3><table>%s</table></div>' % (
            g["color"], esc(g["code"]), esc(g["label"]), body))
    return "".join(cols)


def short_key(k):
    return (k.replace(" (comma)", "").replace(" (period)", "").replace(" (semicolon)", "").replace(" (quote)", "")
             .replace(" (minus)", "").replace(" (equals)", "").replace("Joystick 1, left / right axis", "Joystick 1 X").replace("Joystick 1, forward / back axis", "Joystick 1 Y")
             .replace("Page Up", "PgUp").replace("Page Down", "PgDn").replace(" arrow", ""))


