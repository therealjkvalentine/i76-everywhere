def read(path):
    with open(path, encoding="utf-8", errors="replace", newline="") as f:
        return f.read().replace("\r\n", "\n")


# ----------------------------------------------------------------------------- input.map
def parse_map_text(text):
    """[{action, lines: [[sign, device, token], ...]}, ...] in file order."""
    blocks, action, cur = [], None, None
    for raw in text.split("\n"):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        m = re.match(r"^(\S+)\s*{", line)
        if m:
            action, cur = m.group(1), []
            continue
        if line.startswith("}"):
            if action is not None:
                blocks.append({"action": action, "lines": cur})
            action, cur = None, None
            continue
        m = re.match(r"^([+-])\s+(\S+)\s+(\S+)$", line)
        if m and cur is not None:
            cur.append([m.group(1), m.group(2), m.group(3)])
    return blocks


class Binding:
    """One block of the map: an action and how it is triggered."""
    def __init__(self, action, lines):
        self.action = action.lower()
        self.analog = None
        self.dev = self.tok = None
        self.mods = frozenset()
        analog = [l for l in lines if "/" in l[2]]
        if analog:
            self.analog = (analog[0][1].lower(), analog[0][2])
            return
        plus = [l for l in lines if l[0] == "+"]
        main = [l for l in plus if not (l[1].lower() == "keyboard" and l[2].lower() in MODS)]
        self.mods = frozenset(l[2].lower() for l in plus if l[1].lower() == "keyboard" and l[2].lower() in MODS)
        if main:
            self.dev, self.tok = main[0][1].lower(), main[0][2]

    @property
    def chord(self):
        return (self.dev, self.tok.lower(), self.mods) if self.tok else None


def bindings_of(blocks):
    return [Binding(b["action"], b["lines"]) for b in blocks]


def index_by_key(bindings):
    """(device, token.lower()) -> [action, ...] for bindings WITHOUT a modifier chord."""
    idx = {}
    for b in bindings:
        if b.tok and not b.mods:
            idx.setdefault((b.dev, b.tok.lower()), []).append(b.action)
    return idx


# ----------------------------------------------------------------------------- AutoHotkey
DIGITS = {"1": "One", "2": "Two", "3": "Three", "4": "Four", "5": "Five",
          "6": "Six", "7": "Seven", "8": "Eight", "9": "Nine", "0": "Zero"}
AHK_NAMED = {"enter": "Enter", "tab": "Tab", "space": "Space", ".": "Period", ",": "Comma",
             "-": "Minus", "=": "Equal", "up": "GreyUpArrow", "down": "GreyDownArrow",
             "left": "GreyLeftArrow", "right": "GreyRightArrow"}


def ahk_key(k):
    """An AutoHotkey key name -> ('keyboard'|'mouse'|'fixed', map token)."""
    kl = k.lower()
    if kl == "lbutton":
        return ("mouse", "LeftBtn")
    if kl in ("esc", "escape"):
        return ("fixed", "Esc")
    if re.fullmatch(r"f\d+", kl):
        return ("fixed", k.upper())
    if k in DIGITS:
        return ("keyboard", DIGITS[k])
    if kl in AHK_NAMED:
        return ("keyboard", AHK_NAMED[kl])
    if re.fullmatch(r"[a-z]", kl):
        return ("keyboard", k.upper())
    return ("keyboard", k)          # already a map token (the Fighterstick tables use those)


def ahk_table(src, name):
    """gName := {1: "h", 2: "Enter" ...} with ', ...' continuation lines -> {key: value}."""
    m = re.search(r"^%s\s*:=\s*\{(.*?)\}" % re.escape(name), src, re.M | re.S)
    if not m:
        return None
    out = {}
    for k, s, n in re.findall(r"(\d+)\s*:\s*(?:\"([^\"]*)\"|(\d+))", m.group(1)):
        out[k] = s if s != "" or not n else n
    return out


def parse_remap(src):
    r = {"findings": []}
    for name in ("gWheelBase", "gWheelAlt", "gWheelHoldSet", "gWheelHat", "gWheelHatAlt"):
        r[name] = ahk_table(src, name)
        if r[name] is None:
            r["findings"].append("i76-remap.ahk: table %s not found (the parser needs '%s := {...}')" % (name, name))
            r[name] = {}
    m = re.search(r"^gWheelShiftBtn\s*:=\s*(\d+)", src, re.M)
    r["shift_btn"] = m.group(1) if m else None
    if not m:
        r["findings"].append("i76-remap.ahk: gWheelShiftBtn not found")
    r["xbuttons"] = dict(re.findall(r"^(XButton\d)::(\S+)", src, re.M))
    r["pad_lines"] = {}
    for m in re.finditer(r"^;\s*@pad\s+([^:]+):\s*(.+)$", src, re.M):
        r["pad_lines"][m.group(1).strip()] = m.group(2).strip()
    # keys the pad code sends: the XIPoll section up to the rumble mixer, plus the right-stick glance
    keys = set()
    a = src.find("\nXIPoll:")
    b = src.find("; ---- rumble mixer", a)
    if a < 0 or b < 0:
        r["findings"].append("i76-remap.ahk: XIPoll section (from 'XIPoll:' to '; ---- rumble mixer') not found")
    else:
        sec = "\n".join(l.split(" ;", 1)[0] for l in src[a:b].split("\n") if not l.lstrip().startswith(";"))
        keys |= set(re.findall(r"RSGSet\(\"([^\"]+)\"", sec))
        for k in re.findall(r"^\s*SendEvent,\s*(\S+)\s*$", sec, re.M):
            k = k.strip("{}")
            if "%" not in k:
                keys.add(k)
        if re.search(r"^\s*Click\s*$", sec, re.M):
            keys.add("LButton")
        for lst in re.findall(r"StrSplit\(\"([^\"]+)\"", sec):
            keys |= set(lst.split(","))
        for x, y in re.findall(r"\?\s*\"(F\d+)\"\s*:\s*\"(F\d+)\"", sec):
            keys |= {x, y}
    g = re.search(r"^RStickGlance:(.*?)^return", src, re.M | re.S)
    if g:
        keys |= set(re.findall(r"RSGHys\(\"([^\"]+)\"", g.group(1)))
    r["pad_keys"] = keys
    return r


def parse_stick(src):
    s = {"btn": {}, "pov": [], "axis": [], "findings": []}
    for n, ctl, act, key in re.findall(
            r"^BTN\[(\d+)\]\s*:=\s*\{ctl:\s*\"([^\"]*)\",\s*act:\s*\"([^\"]*)\",\s*key:\s*\"([^\"]*)\"\}", src, re.M):
        s["btn"][int(n)] = {"ctl": ctl.strip(), "act": act, "key": key}
    for ctl, act, key in re.findall(
            r"^POV\.Push\(\{ctl:\s*\"([^\"]*)\",\s*act:\s*\"([^\"]*)\",\s*key:\s*\"([^\"]*)\"\}\)", src, re.M):
        s["pov"].append({"ctl": ctl.strip(), "act": act, "key": key})
    for body in re.findall(r"^AXIS\.Push\(\{(.*?)\}\)", src, re.M):
        d = dict(re.findall(r"(\w+):\s*\"?([^\",]+)\"?", body))
        s["axis"].append({k: v.strip() for k, v in d.items()})
    if not s["btn"] or len(s["pov"]) != 4 or len(s["axis"]) != 4:
        s["findings"].append("i76-ch-fighterstick.ahk: expected BTN[n] entries, 4 POV.Push and 4 AXIS.Push lines; found %d / %d / %d"
                             % (len(s["btn"]), len(s["pov"]), len(s["axis"])))
    return s


def parse_play(src):
    out = {}
    for name in ("WheelUp", "WheelDown"):
        m = re.search(r"\[string\]\$%s\s*=\s*\"([^\"]*)\"" % name, src)
        out[name] = m.group(1) if m else None
    return out


# ----------------------------------------------------------------------------- the model + checks
class Model:
    pass


def load():
    M = Model()
    M.findings = []
    M.data = json.loads(read(DATA))
    M.map_bytes = open(MAP, "rb").read()
    M.map_md5 = hashlib.md5(M.map_bytes).hexdigest()
    M.blocks = parse_map_text(read(MAP))
    M.bindings = bindings_of(M.blocks)
    M.by_key = index_by_key(M.bindings)
    M.stock = json.loads(read(STOCK))
    M.stock_bindings = bindings_of(M.stock["blocks"])
    M.remap = parse_remap(read(REMAP))
    M.stick = parse_stick(read(STICK))
    M.play = parse_play(read(PLAY))
    M.findings += M.remap["findings"] + M.stick["findings"]
    M.actions = {k.lower(): v for k, v in M.data["actions"].items() if not k.startswith("_")}
    M.stock_only = {k.lower(): v for k, v in M.data["stock_only_actions"].items() if not k.startswith("_")}
    M.fixed = {k: v for k, v in M.data["fixed_keys"].items() if not k.startswith("_")}
    M.groups = {g["id"]: g for g in M.data["groups"]}
    M.known = {e["id"]: e["what"] for e in M.data["known_mismatches"]["list"]}
    M.mismatches = {}            # id -> text, the ones actually found
    return M


def label(M, action):
    a = M.actions.get(action) or M.stock_only.get(action)
    return a["label"] if a else action


def resolve(M, layer, control, key, expect):
    """What a key sent by a layer does on the map. Records findings / mismatches.
    Returns (text, ok): text for the sheet, ok False when the key does nothing."""
    dev, tok = ahk_key(key)
    if dev == "fixed":
        if tok not in M.fixed:
            M.findings.append("%s %s sends %s, which is not in the map and not under fixed_keys in controls-sheet.json" % (layer, control, tok))
            return (tok, False)
        if expect:
            M.findings.append("%s %s: controls-sheet.json expects action '%s' but %s is an engine key outside the map (expect must be null)" % (layer, control, expect, tok))
        return (M.fixed[tok]["label"], True)
    acts = M.by_key.get((dev, tok.lower()), [])
    exp = expect.lower() if expect else None
    if exp and exp not in M.actions and exp not in M.stock_only:
        M.findings.append("%s %s: controls-sheet.json expects '%s', which is not an action name known to this file" % (layer, control, expect))
    if not acts:
        mid = "%s:%s:%s" % (layer, control, tok)
        what = "%s %s sends %s%s; the map binds nothing to that key" % (
            layer, control, pretty(tok), (" (meant: %s)" % label(M, exp)) if exp else "")
        M.mismatches[mid] = what
        if mid not in M.known:
            M.findings.append("KEY NOT BOUND IN THE MAP: %s. Bind it in controls/input.map, change the layer, or list id '%s' under known_mismatches" % (what, mid))
        return ((label(M, exp) if exp else pretty(tok)), False)
    if exp and exp not in acts:
        M.findings.append("%s %s sends %s, which the map binds to %s; controls-sheet.json says it is meant to be '%s'" % (
            layer, control, pretty(tok), " + ".join(acts), exp))
    return (" + ".join(dict.fromkeys(label(M, a) for a in acts)), True)


def check(M):
    F = M.findings
    map_actions = {b.action for b in M.bindings}
    # 1. data <-> map
    for a in sorted(set(M.actions) - map_actions):
        F.append("action '%s' is in controls-sheet.json but not in controls/input.map" % a)
    for a in sorted(map_actions - set(M.actions)):
        F.append("action '%s' is in controls/input.map but has no entry in controls-sheet.json (add its label and group)" % a)
    for a, v in list(M.actions.items()) + list(M.stock_only.items()) + list(M.fixed.items()):
        if v.get("group") not in M.groups:
            F.append("'%s': unknown group '%s' in controls-sheet.json" % (a, v.get("group")))
    for a in sorted(M.stock_only):
        if a in map_actions:
            F.append("'%s' is under stock_only_actions but controls/input.map binds it: move it to actions" % a)
    stock_actions = {b.action for b in M.stock_bindings}
    for a in sorted(stock_actions - set(M.actions) - set(M.stock_only)):
        F.append("stock action '%s' has no label (add it to actions or stock_only_actions)" % a)

    # 3. shared keys
    allowed = [set(x.lower() for x in s) for s in M.data["allow_shared_keys"]["sets"]]
    by_chord = {}
    for b in M.bindings:
        if b.chord:
            by_chord.setdefault(b.chord, set()).add(b.action)
    for chord, acts in sorted(by_chord.items(), key=str):
        if len(acts) > 1 and not any(acts <= s for s in allowed):
            F.append("actions %s share %s in the map and are not an allowed set (allow_shared_keys)" % (
                " + ".join(sorted(acts)), chord_text(chord[1], chord[2], chord[0])))
    for b in M.bindings:
        if b.analog is None and b.tok is None:
            F.append("block '%s' in the map has no '+' line: nothing triggers it" % b.action)

    # mouse (2, 4)
    M.mouse_rows = []
    for tok, name in (("LeftBtn", "Left button"), ("MiddleBtn", "Middle button"), ("RightBtn", "Right button")):
        acts = M.by_key.get(("mouse", tok.lower()), [])
        M.mouse_rows.append((name, " + ".join(label(M, a) for a in acts) if acts else "not bound", "", True))
    md = M.data["mouse"]
    for xb in ("XButton1", "XButton2"):
        key = M.remap["xbuttons"].get(xb)
        if key is None:
            F.append("i76-remap.ahk has no '%s::' line but controls-sheet.json lists it under mouse" % xb)
            continue
        text, ok = resolve(M, "mouse", xb, key, md[xb]["expect"])
        M.mouse_rows.append((md[xb]["name"], text, "key " + pretty(ahk_key(key)[1]), ok))
    for extra in sorted(set(M.remap["xbuttons"]) - {"XButton1", "XButton2"}):
        F.append("i76-remap.ahk remaps %s, which controls-sheet.json does not list under mouse" % extra)
    for w in ("WheelUp", "WheelDown"):
        key = M.play.get(w)
        if not key:
            F.append("PLAY-i76.ps1: default of -%s not found" % w)
            continue
        text, ok = resolve(M, "mouse", w, key, md[w]["expect"])
        M.mouse_rows.append((md[w]["name"], text, "key " + pretty(ahk_key(key)[1]), ok))

    # gamepad (2, 4)
    gp = M.data["gamepad"]
    used_at, claimed = set(), set()
    M.pad = {}                    # control -> {"base": [...], "shift": [...]}
    for e in gp["entries"]:
        at = e["at"]
        used_at.add(at)
        line = M.remap["pad_lines"].get(at)
        if line is None:
            F.append("gamepad entry '%s': i76-remap.ahk has no '@pad %s:' line" % (e["control"], at))
            line = ""
        if len(e["sends"]) != len(e["expect"]):
            F.append("gamepad entry at '%s': 'sends' and 'expect' differ in length" % at)
            continue
        at_sent = {ahk_key(k) for e2 in gp["entries"] if e2["at"] == at for k in e2["sends"]}
        for hint in re.findall(r"\(([A-Z]|[-=]|Esc)\)", line):
            if ahk_key(hint if len(hint) > 1 else hint.lower()) not in at_sent:
                F.append("gamepad '@pad %s' names key (%s) but the controls-sheet.json entries for it send %s" % (at, hint, e["sends"]))
        parts, ok_all = [], True
        for k, exp in zip(e["sends"], e["expect"]):
            if k not in M.remap["pad_keys"]:
                F.append("gamepad entry at '%s' says it sends '%s', but the XIPoll code in i76-remap.ahk never sends that key" % (at, k))
            claimed.add(k)
            text, ok = resolve(M, "gamepad", at, k, exp)
            ok_all = ok_all and ok
            if text not in parts:
                parts.append(text)
        text = e.get("label") or " + ".join(parts)
        keys = " ".join(pretty(ahk_key(k)[1]) for k in e["sends"])
        M.pad.setdefault(e["control"], {"base": [], "shift": []})[e["layer"]].append(
            {"text": text, "how": e.get("how", ""), "keys": keys, "ok": ok_all})
    for at in sorted(set(M.remap["pad_lines"]) - used_at):
        F.append("i76-remap.ahk has '@pad %s: %s' but controls-sheet.json has no gamepad entry for it" % (at, M.remap["pad_lines"][at]))
    for k in sorted(M.remap["pad_keys"] - claimed):
        F.append("the XIPoll code in i76-remap.ahk sends '%s', which no gamepad entry in controls-sheet.json claims" % k)
    # native pad bindings in the map
    M.native_joy = [b for b in M.bindings if (b.analog and b.analog[0].startswith("joystick")) or (b.dev or "").startswith("joystick")]
    for b in M.native_joy:
        if not b.analog:
            F.append("the map binds %s %s natively to '%s'; the sheet's gamepad / wheel pages assume the layers own every button (docs/WHEEL-T300.md: a native binding beside the layer fires twice)" % (b.dev, b.tok, b.action))

    # wheel (2, 4)
    wd = M.data["wheel"]
    base, alt, hold = M.remap["gWheelBase"], M.remap["gWheelAlt"], M.remap["gWheelHoldSet"]
    nums = set(base) | set(alt) | ({M.remap["shift_btn"]} if M.remap["shift_btn"] else set())
    for n in sorted(nums - set(wd["buttons"]), key=int):
        F.append("i76-remap.ahk has wheel button %s; controls-sheet.json wheel.buttons has no entry for it" % n)
    for n in sorted(set(wd["buttons"]) - nums, key=int):
        F.append("controls-sheet.json wheel.buttons lists button %s; i76-remap.ahk's gWheelBase / gWheelAlt do not" % n)
    M.wheel_rows = []
    for n in sorted(set(wd["buttons"]) & nums, key=int):
        d = wd["buttons"][n]
        if n == M.remap["shift_btn"]:
            if d["base"] != "SHIFT":
                F.append("wheel button %s is gWheelShiftBtn in i76-remap.ahk; controls-sheet.json says base '%s'" % (n, d["base"]))
            M.wheel_rows.append((n, d["name"], ("SHIFT (hold)", "", True), ("", "", True)))
            continue
        cells = []
        for layer, table in (("base", base), ("shift", alt)):
            key = table.get(n)
            if key is None:
                if d.get(layer):
                    F.append("wheel button %s %s: controls-sheet.json expects '%s' but the .ahk table has no key" % (n, layer, d[layer]))
                cells.append(("", "", True))
                continue
            text, ok = resolve(M, "wheel", "%s%s" % ("" if layer == "base" else "shift+", n), key, d.get(layer))
            cells.append((text, pretty(ahk_key(key)[1]), ok))
        M.wheel_rows.append((n, d["name"], cells[0], cells[1]))
    M.wheel_hat = []
    for ang in ("0", "9000", "18000", "27000"):
        d = wd["hat"][ang]
        cells = []
        for layer, table in (("base", M.remap["gWheelHat"]), ("shift", M.remap["gWheelHatAlt"])):
            key = table.get(ang)
            if key is None:
                if d.get(layer):
                    F.append("wheel hat %s %s: controls-sheet.json expects '%s' but the .ahk table has no key" % (d["name"], layer, d[layer]))
                cells.append(("", "", True))
                continue
            if not d.get(layer):
                F.append("wheel hat %s %s: the .ahk sends '%s' but controls-sheet.json expects nothing" % (d["name"], layer, key))
            text, ok = resolve(M, "wheel", "%shat-%s" % ("" if layer == "base" else "shift+", ang), key, d.get(layer))
            cells.append((text, pretty(ahk_key(key)[1]), ok))
        M.wheel_hat.append((d["name"], cells[0], cells[1]))

    # stick (2, 4): the script's own tables carry the action; it must be what the map binds the key to
    def stick_cell(kind, e):
        text, ok = resolve(M, "stick", "%s %s" % (kind, e.get("ctl", "")), e["key"], e["act"])
        return {"ctl": e.get("ctl", ""), "text": text, "key": pretty(ahk_key(e["key"])[1]), "ok": ok, "mode": e.get("mode", "")}
    M.stick_btn = {n: stick_cell("button", e) for n, e in M.stick["btn"].items()}
    M.stick_pov = [stick_cell("POV", e) for e in M.stick["pov"]]
    M.stick_axis = [stick_cell("axis", e) for e in M.stick["axis"]]
    sd = M.data["stick"]
    drawn = set(sd["grip_buttons"]) | {b for h in sd["hats"] for b in h["buttons"]}
    for n in sorted(set(M.stick["btn"]) - drawn):
        F.append("i76-ch-fighterstick.ahk has BTN[%d]; controls-sheet.json stick.hats / grip_buttons does not place it on the page" % n)
    for n in sorted(drawn - set(M.stick["btn"])):
        F.append("controls-sheet.json places stick button %d on the page; i76-ch-fighterstick.ahk has no BTN[%d]" % (n, n))

    # 5. the known-mismatch list must stay true
    for mid in sorted(set(M.known) - set(M.mismatches)):
        F.append("known_mismatches lists '%s' but the checker no longer finds it: remove the entry" % mid)
    return F


