"""Build the printable controls quick reference, and check that the control sources agree.

    python tools/controls-sheet/build_sheet.py            check, then write controls-sheet.html
                                                          and refresh the generated table in
                                                          docs/CONTROLS.md
    python tools/controls-sheet/build_sheet.py --check    check only (also: is the CONTROLS.md
                                                          table current?). Exit 1 on any finding.
    python tools/controls-sheet/build_sheet.py --extract-stock <GOG input.map>
                                                          rewrite stock-2.1.0.17.json

Standard library only. tools\\controls-sheet\\build.ps1 runs this, the input.map lint and the PDF.

Sources, each read fresh on every run (nothing is copied by hand that can be parsed):
  controls/input.map            native bindings (keyboard, mouse buttons, analog axes)
  i76-remap.ahk                 wheel tables (gWheelBase / gWheelAlt / gWheelHat / gWheelHatAlt /
                                gWheelHoldSet), mouse buttons 4 / 5 (XButton1 / XButton2), the
                                '@pad' lines and the keys the XIPoll code sends
  i76-ch-fighterstick.ahk       BTN / POV / AXIS tables (control, action, key)
  PLAY-i76.ps1                  -WheelUp / -WheelDown defaults (mouse wheel)
  controls-sheet.json           labels, groups, physical names, what each layer control is MEANT
                                to do, the allow-list of shared keys, the known mismatches
  stock-2.1.0.17.json           GOG's 1997 bindings, for the comparison page

The build FAILS (exit 1, every finding listed) when:
  1. an action in controls-sheet.json is not in the map, or an action in the map has no entry;
  2. a key a layer sends is not bound in the map (unless listed under known_mismatches);
  3. two actions share a key in the map and are not an allowed set;
  4. controls-sheet.json disagrees with the parsed .ahk (a pad entry without its @pad line, a
     @pad line without an entry, a key the code sends that no entry claims, a key bound to a
     different action than 'expect' says, a wheel button the tables do not have ...);
  5. a known_mismatches entry is no longer a mismatch (the list must stay true).
"""
